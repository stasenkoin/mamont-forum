// ─── ЧТО ДЕЛАЕТ ЭТОТ ФАЙЛ ───────────────────────────────────────────────────
// Создаёт декоратор @Roles() — метка для эндпоинтов которые требуют
// определённую роль. Используется вместе с RolesGuard: guard читает
// какие роли указаны и проверяет есть ли они у текущего пользователя.
// ────────────────────────────────────────────────────────────────────────────

import { SetMetadata } from '@nestjs/common';

// Строка-ключ под которым список ролей будет сохранён в метаданных маршрута.
// RolesGuard читает метаданные именно по этому ключу через Reflector.
export const ROLES_KEY = 'roles';

// @Roles('ADMIN') или @Roles('ADMIN', 'MODERATOR') — принимает любое количество ролей.
// SetMetadata записывает { roles: ['ADMIN'] } в метаданные маршрута.
// RolesGuard затем читает этот массив и проверяет есть ли хоть одна из этих ролей
// у текущего пользователя в SuperTokens.
export const Roles = (...roles: string[]) => SetMetadata(ROLES_KEY, roles);
