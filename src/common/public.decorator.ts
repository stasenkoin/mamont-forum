// ─── ЧТО ДЕЛАЕТ ЭТОТ ФАЙЛ ───────────────────────────────────────────────────
// Создаёт декоратор @Public() — метка для эндпоинтов которые доступны
// без авторизации. Используется вместе с AuthGuard: guard видит эту метку
// и пропускает запрос без проверки токена.
// ────────────────────────────────────────────────────────────────────────────

import { SetMetadata } from '@nestjs/common';

// Строка-ключ под которым метка будет сохранена в метаданных маршрута.
// Guard читает метаданные именно по этому ключу через Reflector.
export const IS_PUBLIC = 'isPublic';

// @Public() — декоратор который вешается на метод контроллера или весь контроллер.
// SetMetadata записывает { isPublic: true } в метаданные этого маршрута.
// Guard затем читает эти метаданные и если isPublic === true — пропускает без проверки.
export const Public = () => SetMetadata(IS_PUBLIC, true);
